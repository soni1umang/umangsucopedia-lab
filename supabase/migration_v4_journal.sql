-- Ucopedia daily journal. Run once in Supabase SQL Editor.
-- Private pages can only be read/edited by an admin; public pages may be read by anyone.
create table if not exists public.journal_entries (
  id bigint generated by default as identity primary key,
  entry_date date not null unique,
  title text not null default '',
  body text not null default '',
  photos jsonb not null default '[]'::jsonb,
  published boolean not null default false,
  updated_at timestamptz not null default now(),
  constraint journal_photos_max_two check (jsonb_typeof(photos) = 'array' and jsonb_array_length(photos) <= 2)
);

alter table public.journal_entries enable row level security;
drop policy if exists "public read published journal pages" on public.journal_entries;
create policy "public read published journal pages"
on public.journal_entries for select using (published = true or public.is_admin());
drop policy if exists "admin manage journal pages" on public.journal_entries;
create policy "admin manage journal pages"
on public.journal_entries for all using (public.is_admin()) with check (public.is_admin());

create index if not exists journal_entries_date_idx on public.journal_entries(entry_date desc);
